// Type-check every compiler-emitted native type attempt in one C++-target Haxe consumer. This is
// intentionally broader than the compile/run-proven API: it keeps unproven carriers visible while
// proving that the generated Haxe names, aliases, and hidden extern modules form one coherent tree.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { spawnSync } from 'node:child_process';

const root = path.join(import.meta.dirname, '..', '..');
const report = JSON.parse(readFileSync(path.join(root, 'src-cpp', 'type-attempts.json'), 'utf8'));
if (report.schema !== 'flight-hx-native-type-attempts/1') fail(`unknown report schema ${String(report.schema)}`);

const temporaryRoot = mkdtempSync(path.join(tmpdir(), 'flight-hx-native-type-attempts-'));
try {
  const source = [
    '// Generated by tests/gates/nativeTypeAttempts.mjs.',
    'class NativeTypeAttempts {',
    '  static function main():Void {}',
    ...report.declarations.map(({ genericArity, publicName, status }, index) => {
      const baseName =
        status === 'native-only-disambiguation' ? publicName.replace(/^flight\./u, 'flight._cpp.') : publicName;
      const typeName = genericArity > 0 ? `${baseName}<${Array(genericArity).fill('Dynamic').join(', ')}>` : baseName;
      return `  @:keep static function accept${String(index)}(value:${typeName}):${typeName} return value;`;
    }),
    ...report.collisionAliases.map(({ genericArity, publicName }, index) => {
      const typeName = genericArity > 0 ? `${publicName}<${Array(genericArity).fill('Dynamic').join(', ')}>` : publicName;
      return `  @:keep static function acceptCollision${String(index)}(value:${typeName}):${typeName} return value;`;
    }),
    ...report.internalCarriers.map(({ haxeName, parameters }, index) => {
      const typeName = parameters ? `flight._internal.${haxeName}<Dynamic>` : `flight._internal.${haxeName}`;
      return `  @:keep static function acceptInternal${String(index)}(value:${typeName}):${typeName} return value;`;
    }),
    ...report.hostCarriers.map(({ haxeName }, index) =>
      `  @:keep static function acceptHost${String(index)}(value:flight.${haxeName}):flight.${haxeName} return value;`,
    ),
    '}',
    '',
  ].join('\n');
  writeFileSync(path.join(temporaryRoot, 'NativeTypeAttempts.hx'), source);

  const haxeRoot = path.join(root, '.haxe', '4.3.7');
  const haxe = path.join(haxeRoot, process.platform === 'win32' ? 'haxe.exe' : 'haxe');
  const environment = {
    ...process.env,
    HAXELIB_PATH: path.join(root, '.haxelib'),
    HAXE_STD_PATH: path.join(haxeRoot, 'std'),
    PATH: `${haxeRoot}${path.delimiter}${process.env.PATH ?? ''}`,
  };
  const result = spawnSync(
    haxe,
    [
      '-cp',
      path.join(root, 'src'),
      '-cp',
      path.join(root, 'src-cpp'),
      '-cp',
      temporaryRoot,
      '--main',
      'NativeTypeAttempts',
      '-cpp',
      path.join(temporaryRoot, 'cpp'),
      '--no-output',
      '-D',
      `flight_cpp_root=${path.join(root, '.dependencies', 'flight-cpp')}`,
      '-D',
      `flight_hx_root=${root}`,
    ],
    { cwd: temporaryRoot, encoding: 'utf8', env: environment },
  );
  if (result.status !== 0) fail(`complete native type attempt surface does not type-check:\n${result.stdout}${result.stderr}`);

  process.stdout.write(
    `native-type-attempt gate: all ${String(report.summary.totalAttempts)} symbol-backed type attempts ` +
      `(${String(report.summary.publicAliases)} unified aliases, ` +
      `${String(report.summary.collisionAliases)} canonical collision aliases, ` +
      `${String(report.summary.internalCarriers)} native runtime carriers, ` +
      `${String(report.summary.hostCarriers)} unified host carriers, ` +
      `${String(report.summary.templateAdapters)} generic reference-template adapters, ` +
      `${String(report.summary.symbolBackedRefusals)} formerly refused by the compiler, ` +
      `${String(report.summary.nativeOnlyDisambiguations)} native-only collision names, ` +
      `${String(report.summary.maintainedOverrides)} maintained handles) type-check on the C++ target.\n`,
  );
} finally {
  rmSync(temporaryRoot, { force: true, recursive: true });
}

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}
