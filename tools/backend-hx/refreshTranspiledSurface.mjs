import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { buildTranspiledBackendSurface } from './haxeSurface.mjs';

// The transpiled implementation corpus can remain pinned while the complete extern SDK advances.
// This refresh derives the honest public subset at their intersection without invoking the
// TypeScript compiler or changing a single compiler-emitted implementation file.

const derivedHeader = '// Generated by tools/backend-hx from the compiler-emitted public surface. Do not edit.\n';
const root = path.resolve(import.meta.dirname, '..', '..');
const externRoot = path.join(root, 'generated', 'js');
const transpiledRoot = path.join(root, 'generated', 'hx');
const options = process.argv.slice(2);
const check = options.includes('--check');
const unknown = options.filter((option) => option !== '--check');

if (unknown.length > 0) {
  process.stderr.write(`Unknown transpiled-surface refresh option(s): ${unknown.join(', ')}\n`);
  process.exit(2);
}

const externManifest = readJson(path.join(externRoot, 'manifest.json'));
const transpiledManifest = readJson(path.join(transpiledRoot, 'manifest.json'));
validateManifests(externManifest, transpiledManifest);

const externFiles = loadHaxeFiles(externRoot);
const transpiledFiles = loadHaxeFiles(transpiledRoot);
const rawTranspiledFiles = transpiledFiles.filter((file) => !file.contents.startsWith(derivedHeader));
const existingDerivedFiles = new Map(
  transpiledFiles.filter((file) => file.contents.startsWith(derivedHeader)).map((file) => [file.path, file.contents]),
);
const rawPaths = new Set(rawTranspiledFiles.map((file) => file.path));
const surface = buildTranspiledBackendSurface(externFiles, rawTranspiledFiles);
const nextDerivedFiles = new Map(surface.files.map((file) => [file.path, file.contents]));
const collisions = [...nextDerivedFiles.keys()].filter((filename) => rawPaths.has(filename)).sort(compareText);

if (collisions.length > 0) {
  throw new Error(`Derived public surface collides with compiler-emitted file(s): ${collisions.join(', ')}`);
}

const provenance = {
  schema: 'flight-hx-transpiled-public-derivation/1',
  externCompilerRevision: externManifest.compiler.revision,
  externSourceRevision: externManifest.source.revision,
  transpiledCompilerRevision: transpiledManifest.compiler.revision,
  transpiledSourceRevision: transpiledManifest.source.revision,
};
const publicSurface = {
  schema: surface.report.schema,
  provenance,
  summary: surface.report.summary,
  supported: surface.report.supported,
  unavailable: surface.report.unavailable,
};
const manifest = {
  ...transpiledManifest,
  publicSurface: provenance,
  summary: {
    ...transpiledManifest.summary,
    compatibilityFiles: surface.files.length,
    generatedFiles: transpiledManifest.summary.emittedFiles + surface.files.length,
    publicRuntimeSurface: surface.report.summary,
  },
};
const expectedMetadata = new Map([
  ['manifest.json', json(manifest)],
  ['public-surface.json', json(publicSurface)],
  ['README.md', generatedReadme(manifest)],
]);
const drift = compareDerivedFiles(existingDerivedFiles, nextDerivedFiles);
for (const [filename, contents] of expectedMetadata) {
  const actual = readFileSync(path.join(transpiledRoot, filename), 'utf8');
  if (actual !== contents) drift.push(filename);
}
drift.sort(compareText);

if (check) {
  if (drift.length > 0) {
    process.stderr.write(`Transpiled public surface differs in ${String(drift.length)} path(s):\n`);
    for (const filename of drift.slice(0, 20)) process.stderr.write(`- ${filename}\n`);
    if (drift.length > 20) process.stderr.write(`- … and ${String(drift.length - 20)} more\n`);
    process.stderr.write('Run `npm run refresh:transpile-surface` and commit generated/hx/.\n');
    process.exit(1);
  }
  process.stdout.write(summaryLine('is current', manifest));
  process.exit(0);
}

for (const filename of existingDerivedFiles.keys()) {
  if (!nextDerivedFiles.has(filename)) rmSync(path.join(transpiledRoot, filename));
}
for (const [filename, contents] of nextDerivedFiles) write(path.join(transpiledRoot, filename), contents);
for (const [filename, contents] of expectedMetadata) write(path.join(transpiledRoot, filename), contents);
process.stdout.write(summaryLine('updated', manifest));

function validateManifests(extern, transpiled) {
  if (extern.schema !== 'flight-hx-generated-sdk/1' || extern.compiler?.emissionMode !== 'extern') {
    throw new Error('generated/js does not contain a supported extern SDK manifest');
  }
  if (transpiled.schema !== 'flight-hx-generated-sdk/1' || transpiled.compiler?.emissionMode !== 'transpile') {
    throw new Error('generated/hx does not contain a supported transpiled SDK manifest');
  }
  if (extern.source?.revision !== transpiled.source?.revision) {
    throw new Error(
      `Extern source ${String(extern.source?.revision)} does not match transpiled source ${String(transpiled.source?.revision)}`,
    );
  }
  if (!Number.isInteger(transpiled.summary?.emittedFiles)) {
    throw new Error('Transpiled SDK manifest has no compiler-emitted file count');
  }
}

function compareDerivedFiles(actual, expected) {
  const drift = [];
  for (const [filename, contents] of expected) {
    if (actual.get(filename) !== contents) drift.push(filename);
  }
  for (const filename of actual.keys()) {
    if (!expected.has(filename)) drift.push(filename);
  }
  return drift;
}

function generatedReadme(manifest) {
  const summary = manifest.summary;
  const provenance = manifest.publicSurface;
  return `# Generated transpiled Haxe SDK

This tree combines compiler-emitted implementations from \`${manifest.source.package}\` ${manifest.source.version} at
\`${manifest.source.revision}\`, produced by \`flight-compiler\` at \`${manifest.compiler.revision}\`, with a public
\`flight.*\` partition derived from the current extern SDK at compiler revision
\`${provenance.externCompilerRevision}\`. Do not edit it by hand.

The transpile compiler emitted ${format(summary.emittedModules)} of ${format(summary.sourceModules)} dependency-closed source modules
from ${format(summary.packages)} SDK packages into ${format(summary.emittedFiles)} Haxe files. The flight-hx integration derived
${format(summary.compatibilityFiles)} backing/public files at the exact intersection of those implementations and the
current extern surface. It refused ${format(summary.refusedModules)} modules; every refusal is recorded in
\`refusals.json\`. The exact supported and unavailable public \`flight.*\` partitions, including both
compiler revisions, are recorded in \`public-surface.json\`.

Refresh only the derived public partition from the checked-in compiler output and current extern SDK:

\`\`\`sh
npm run refresh:transpile-surface
npm run refresh:transpile-surface:check
\`\`\`

Regenerating the underlying optional transpiled implementation corpus is a separate compiler-maintenance task:

\`\`\`sh
npm run generate -- --transpile
npm run refresh:transpile-surface
\`\`\`
`;
}

function loadHaxeFiles(directory) {
  return filesUnder(directory)
    .filter((filename) => filename.endsWith('.hx'))
    .map((filename) => ({
      contents: readFileSync(filename, 'utf8'),
      path: portable(path.relative(directory, filename)),
    }));
}

function filesUnder(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const filename = path.join(directory, entry.name);
    return entry.isDirectory() ? filesUnder(filename) : [filename];
  });
}

function write(filename, contents) {
  mkdirSync(path.dirname(filename), { recursive: true });
  writeFileSync(filename, contents);
}

function readJson(filename) {
  return JSON.parse(readFileSync(filename, 'utf8'));
}

function json(value) {
  return `${JSON.stringify(value, undefined, 2)}\n`;
}

function summaryLine(status, manifest) {
  const summary = manifest.summary.publicRuntimeSurface;
  return `Transpiled public surface ${status}: ${String(manifest.summary.compatibilityFiles)} derived files expose ${String(summary.supportedTypes)} types, ${String(summary.supportedFunctions)} functions, and ${String(summary.supportedValues)} values; ${String(summary.unavailableTypes + summary.unavailableFunctions + summary.unavailableValues)} declarations remain explicit.\n`;
}

function format(value) {
  return new Intl.NumberFormat('en-US').format(value);
}

function portable(filename) {
  return filename.split(path.sep).join('/');
}

function compareText(left, right) {
  return left.localeCompare(right, 'en');
}
